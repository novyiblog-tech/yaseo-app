def ai_key(code: str, role: str | None = None) -> str:
    """Находки про ботов приходят кодом robots-blocks-<бот>; словарь описывает их по роли."""
    if code.startswith("robots-blocks-"):
        return f"robots-blocks-{role or 'search'}"
    return code


def tech_entry(code: str) -> Entry | None:
    return TECH.get(code)


def ai_entry(code: str, role: str | None = None) -> Entry | None:
    return AI.get(ai_key(code, role))
